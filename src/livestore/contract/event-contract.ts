import { Cause, Exit, Option, Schema } from "effect";

import { schema, tables } from "../schema";

export const manifestPath = "src/livestore/contract/manifest.json";
export const goldensPath =
  "src/livestore/__tests__/fixtures/event-wire-goldens.json";

const JsonObject = Schema.Record(Schema.String, Schema.Unknown);
type JsonObject = typeof JsonObject.Type;

const EventEntry = Schema.Struct({
  scope: Schema.Literals(["synced", "clientOnly"]),
  args: JsonObject,
});

export const Manifest = Schema.Struct({
  $comment: Schema.String,
  events: Schema.Record(Schema.String, EventEntry),
  tables: Schema.Record(Schema.String, JsonObject),
});
export type Manifest = typeof Manifest.Type;

export const Goldens = Schema.Struct({
  realRows: Schema.Array(
    Schema.Struct({
      name: Schema.String,
      args: Schema.String,
      seqNum: Schema.Number,
    })
  ),
  synthetic: Schema.Array(
    Schema.Struct({
      event: Schema.String,
      variant: Schema.String,
      encodedV3: Schema.String,
    })
  ),
});
export type Goldens = typeof Goldens.Type;

const ObjectArgs = Schema.Struct({
  properties: JsonObject,
  required: Schema.optionalKey(Schema.Array(Schema.String)),
});

const byCodeUnit = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

const canonicalize = (value: unknown): unknown => {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (typeof value !== "object" || value === null) return value;
  return Object.fromEntries(
    Object.entries(value)
      .toSorted(([a], [b]) => byCodeUnit(a, b))
      .map(([key, child]) => [key, canonicalize(child)])
  );
};

const canonicalJson = (value: unknown) => JSON.stringify(canonicalize(value));

export const encodeManifest = (manifest: Manifest) =>
  `${JSON.stringify(canonicalize(manifest), null, 2)}\n`;

const decodeJsonObject = Schema.decodeUnknownSync(JsonObject);

const encodedArgs = (eventSchema: Schema.Top) => {
  const document = Schema.toJsonSchemaDocument(Schema.toEncoded(eventSchema));
  const args = decodeJsonObject(document.schema);
  return Object.keys(document.definitions).length === 0
    ? args
    : { ...args, $defs: document.definitions };
};

export const buildManifest = (): Manifest => ({
  $comment:
    "Generated by `bun run contract` from src/livestore/schema.ts. Do not edit by hand.",
  events: Object.fromEntries(
    [...schema.eventsDefsMap.values()].map((def) => [
      def.name,
      {
        scope: def.options.clientOnly ? "clientOnly" : "synced",
        args: encodedArgs(def.schema),
      },
    ])
  ),
  tables: Object.fromEntries(
    Object.values(tables).map(({ sqliteDef }) => [
      sqliteDef.name,
      {
        columns: Object.entries(sqliteDef.columns).map(([name, column]) => ({
          name,
          type: column.columnType,
          nullable: column.nullable ?? false,
          primaryKey: column.primaryKey ?? false,
          autoIncrement: column.autoIncrement ?? false,
          ...(Option.isSome(column.default) && {
            default: Schema.encodeUnknownSync(column.schema)(
              column.default.value
            ),
          }),
        })),
        indexes: (sqliteDef.indexes ?? []).map((index) => ({
          name: index.name,
          columns: index.columns,
          unique: index.isUnique ?? false,
        })),
      },
    ])
  ),
});

const fieldChanges = (event: string, base: JsonObject, head: JsonObject) => {
  const breaks: string[] = [];
  const added: string[] = [];
  const baseObject = Schema.decodeUnknownOption(ObjectArgs)(base);
  const headObject = Schema.decodeUnknownOption(ObjectArgs)(head);
  if (Option.isNone(baseObject) || Option.isNone(headObject)) {
    if (canonicalJson(base) !== canonicalJson(head)) {
      breaks.push(`${event}: its argument schema changed`);
    }
    return { breaks, added };
  }

  const {
    properties: _baseFields,
    required: _baseRequired,
    ...baseRest
  } = base;
  const {
    properties: _headFields,
    required: _headRequired,
    ...headRest
  } = head;
  if (canonicalJson(baseRest) !== canonicalJson(headRest)) {
    breaks.push(
      `${event}: its argument schema changed from ${canonicalJson(baseRest)} to ${canonicalJson(headRest)}`
    );
  }

  const baseFields = baseObject.value.properties;
  const headFields = headObject.value.properties;
  const baseRequired = new Set(baseObject.value.required ?? []);
  const headRequired = new Set(headObject.value.required ?? []);

  for (const field of Object.keys(baseFields).toSorted(byCodeUnit)) {
    if (!Object.hasOwn(headFields, field)) {
      breaks.push(`${event}: field \`${field}\` was removed`);
    } else if (
      canonicalJson(baseFields[field]) !== canonicalJson(headFields[field])
    ) {
      breaks.push(
        `${event}: field \`${field}\` changed type from ${canonicalJson(baseFields[field])} to ${canonicalJson(headFields[field])}`
      );
    } else if (baseRequired.has(field) && !headRequired.has(field)) {
      breaks.push(
        `${event}: field \`${field}\` became optional, so clients that still require it reject new events`
      );
    } else if (!baseRequired.has(field) && headRequired.has(field)) {
      breaks.push(
        `${event}: field \`${field}\` became required, so old events without it no longer decode`
      );
    }
  }

  for (const field of Object.keys(headFields).toSorted(byCodeUnit)) {
    if (Object.hasOwn(baseFields, field)) continue;
    if (headRequired.has(field)) {
      breaks.push(
        `${event}: new required field \`${field}\`, so old events without it no longer decode`
      );
    } else {
      added.push(field);
    }
  }

  return { breaks, added };
};

export interface ContractReport {
  readonly breaks: ReadonlyArray<string>;
  readonly notes: ReadonlyArray<string>;
}

/**
 * Compare the base branch's manifest with this code's. Deployed events are
 * append-only: a base event must keep its name, scope and every field's
 * encoded shape. New events and new optional fields pass.
 */
export const compareManifests = (
  base: Manifest,
  head: Manifest
): ContractReport => {
  const breaks: string[] = [];
  const notes: string[] = [];
  const headOnly = Object.keys(head.events)
    .filter((name) => !Object.hasOwn(base.events, name))
    .toSorted(byCodeUnit);

  for (const [name, baseEvent] of Object.entries(base.events).toSorted(
    ([a], [b]) => byCodeUnit(a, b)
  )) {
    const headEvent = head.events[name];
    if (headEvent === undefined) {
      const renamedTo = headOnly.filter(
        (candidate) =>
          canonicalJson(head.events[candidate]) === canonicalJson(baseEvent)
      );
      breaks.push(
        renamedTo.length > 0
          ? `${name} was renamed to ${renamedTo.join(" or ")}; old events still carry the old name`
          : `${name} was removed; old events of this type would be skipped on every rebuild`
      );
      continue;
    }
    if (headEvent.scope !== baseEvent.scope) {
      breaks.push(
        `${name}: scope changed from ${baseEvent.scope} to ${headEvent.scope}`
      );
    }
    const changes = fieldChanges(name, baseEvent.args, headEvent.args);
    breaks.push(...changes.breaks);
    for (const field of changes.added) {
      notes.push(`${name}: new optional field \`${field}\``);
    }
  }

  for (const name of headOnly) notes.push(`${name}: new event`);

  const tableNames = new Set([
    ...Object.keys(base.tables),
    ...Object.keys(head.tables),
  ]);
  const changedTables = [...tableNames]
    .filter(
      (table) =>
        canonicalJson(base.tables[table]) !== canonicalJson(head.tables[table])
    )
    .toSorted(byCodeUnit);
  if (changedTables.length > 0) {
    notes.push(
      `Tables changed (${changedTables.join(", ")}): every replica, including each LinkProcessorDO, rebuilds its state from the eventlog after this deploys`
    );
  }

  return { breaks, notes };
};

const describeFailure = (cause: Cause.Cause<unknown>) =>
  Cause.pretty(cause).split("\n").slice(0, 3).join(" ");

/**
 * Replay goldens (normally the base branch's copy) through this code's event
 * schemas: every encoded payload must decode and re-encode byte for byte.
 */
export const replayGoldens = (goldens: Goldens): ReadonlyArray<string> => {
  const cases = [
    ...goldens.realRows.map((row) => ({
      label: `${row.name} production row seqNum ${row.seqNum}`,
      name: row.name,
      wire: row.args,
    })),
    ...goldens.synthetic.map((golden) => ({
      label: `${golden.event} golden (${golden.variant})`,
      name: golden.event,
      wire: golden.encodedV3,
    })),
  ];

  return cases.flatMap(({ label, name, wire }) => {
    const def = schema.eventsDefsMap.get(name);
    if (def === undefined) return [`${label}: no event named ${name}`];
    const decoded = Schema.decodeUnknownExit(Schema.fromJsonString(def.schema))(
      wire
    );
    if (Exit.isFailure(decoded)) {
      return [`${label} no longer decodes: ${describeFailure(decoded.cause)}`];
    }
    const encoded = Schema.encodeUnknownExit(def.schema)(decoded.value);
    if (Exit.isFailure(encoded)) {
      return [`${label} no longer encodes: ${describeFailure(encoded.cause)}`];
    }
    const reEncoded = JSON.stringify(encoded.value);
    return reEncoded === wire
      ? []
      : [`${label} re-encodes differently: ${reEncoded} instead of ${wire}`];
  });
};
